function CategorySlide(
  title: string,
  subtitle: string,
  does: string,
  how: string,
  tools: string[],
  examples: string[],
): SlideDef['content'] {
  return () => (
    <>
      <Kicker>فئة أدوات</Kicker>
      <Title>{title}</Title>
      <Subtitle>{subtitle}</Subtitle>
      <div className="slide-body">
        <div className="grid-2">
          <Card>
            <h3>ماذا تقدّم؟</h3>
            <p>{does}</p>
          </Card>
          <Card>
            <h3>الفكرة التشغيلية باختصار</h3>
            <p>{how}</p>
          </Card>
        </div>
        <div className="tag-list">
          {tools.map((t) => (
            <span key={t} className="tag en">
              {t}
            </span>
          ))}
        </div>
        <Card>
          <h3>أمثلة من بيئة العمل</h3>
          <p>{examples.join(' · ')}</p>
        </Card>
      </div>
    </>
  )
}

